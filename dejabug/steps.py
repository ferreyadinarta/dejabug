"""Turn an event log into user steps: a markdown list and a Playwright test draft."""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

ACTIONS = ("click", "hover", "type")


@dataclass
class Step:
    t: float
    kind: str               # click | hover | type | note
    target: str | None      # visible label, or None when there was no text nearby
    text: str = ""          # typed text, or the note's wording
    zoom: str | None = None


def _items(e: dict) -> str:
    items = e.get("items") or e.get("after") or []
    return ", ".join(items[:3]) + (", ..." if len(items) > 3 else "")


def note_for(e: dict) -> str | None:
    kind = e["type"]
    if kind == "panel_opened":
        return f"a list opened: {_items(e)}"
    if kind == "panel_closed":
        return f"a list closed: {_items(e)}"
    if kind == "content_replaced":
        return f"the list changed to: {_items(e)}"
    if kind == "scroll":
        return f"scrolled {e['direction']} {e['dy_px']} px"
    if kind == "error_shown":
        return f'error shown: "{e["text"]}"'
    if kind == "text_appeared" and len(e["text"]) >= 3:
        return f'"{e["text"]}" appeared'
    if kind == "text_changed":
        return f'"{e["from"]}" changed to "{e["to"]}"'
    if kind == "nav":
        return f"went to {e['to']}"
    return None


def _merge_list_swaps(events: list[dict]) -> list[dict]:
    """A list closing and opening at the same moment is one list changing."""
    out = []
    for e in events:
        if e["type"] == "panel_closed" and any(o["type"] == "panel_opened" and o["t"] == e["t"] for o in events):
            continue
        if e["type"] == "panel_opened" and any(o["type"] == "panel_closed" and o["t"] == e["t"] for o in events):
            e = {**e, "type": "content_replaced", "after": e.get("items", [])}
        out.append(e)
    return out


def _drop_page_context(events: list[dict]) -> list[dict]:
    """Several unrelated texts appearing at once is the page around the bug, not a step."""
    per_t: dict[float, int] = {}
    for e in events:
        if e["type"] == "text_appeared":
            per_t[e["t"]] = per_t.get(e["t"], 0) + 1
    return [e for e in events if not (e["type"] == "text_appeared" and per_t[e["t"]] >= 3)]


UNSEEN = "no click seen before this: a drag, right-click or keyboard shortcut may have happened here"
BIG = ("panel_opened", "panel_closed", "content_replaced", "error_shown", "nav")


def steps_from(events: list[dict]) -> list[Step]:
    out: list[Step] = []
    last_action = -9.0
    flagged: set[float] = set()
    for e in sorted(_merge_list_swaps(_drop_page_context(events)), key=lambda e: e["t"]):
        if e["type"] in BIG and e["t"] - last_action > 1.5 and e["t"] > 0.5 and e["t"] not in flagged:
            flagged.add(e["t"])
            out.append(Step(e["t"], "note", None, UNSEEN))
        if e["type"] == "hover" and not e.get("label"):
            continue  # a hover over nothing nameable tells the reader nothing
        if e["type"] in ACTIONS:
            last_action = e["t"]
            target = e.get("label")
            text = e.get("text", "") if e["type"] == "type" else ""
            out.append(Step(e["t"], e["type"], target, text, e.get("zoom")))
        elif (note := note_for(e)) is not None:
            out.append(Step(e["t"], "note", None, note))
    return out


AI_VERBS = {"click": "Click", "double_click": "Double-click", "right_click": "Right-click", "type": "Type",
            "press": "Press", "paste": "Paste", "drag": "Drag", "select": "Select", "scroll": "Scroll",
            "hover": "Hover over"}


def ai_markdown(data: dict, video: str) -> str:
    """Steps written by a model from the extracted evidence."""
    lines = [f"### Steps to reproduce (from `{video}`)", ""]
    for n, s in enumerate(data.get("steps", []), 1):
        verb = AI_VERBS.get(s.get("action", ""), s.get("action", "").capitalize())
        what = f'"{s["text"]}"' if s.get("text") and s.get("action") in ("type", "paste", "press") else ""
        target = s.get("target") or ""
        if s.get("action") in ("type", "paste") and target:
            line = f"{verb} {what} in {target}"
        elif s.get("action") == "press":
            line = f"{verb} {s.get('text') or target}"
        else:
            line = f"{verb} {target}".strip()
        flag = " _(not sure)_" if s.get("uncertain") else ""
        lines.append(f"{n}. {line} ({float(s.get('t', 0)):.1f}s){flag}")
    bug = data.get("bug") or {}
    if bug:
        lines += ["", f"**Bug** ({float(bug.get('t', 0)):.1f}s): {bug.get('what', '')}"]
    lines += ["", "_Generated by [dejabug](https://github.com/ferreyadinarta/dejabug) from the screen recording; "
              "steps marked \"not sure\" were inferred, not seen._"]
    return "\n".join(lines) + "\n"


def markdown(steps: list[Step], video: str) -> str:
    lines = [f"### Steps to reproduce (from `{video}`)", ""]
    n = 0
    for s in steps:
        if s.kind == "note":
            lines.append(f"   - {s.t:.1f}s: {s.text}")
            continue
        n += 1
        what = {"click": "Click", "hover": "Hover over", "type": "Type"}[s.kind]
        if s.kind == "type":
            lines.append(f'{n}. {what} "{s.text}" ({s.t:.1f}s)')
        elif s.target:
            lines.append(f'{n}. {what} "{s.target}" ({s.t:.1f}s)')
        else:
            lines.append(f"{n}. {what} the element in `{s.zoom}` ({s.t:.1f}s)" if s.zoom else f"{n}. {what} ({s.t:.1f}s)")
    lines += ["", "_Generated by [dejabug](https://github.com/ferreyadinarta/dejabug) from the screen recording._"]
    return "\n".join(lines) + "\n"


def test_draft(steps: list[Step], url: str) -> str:
    body: list[str] = []
    last_t = 0.0
    for s in steps:
        if s.kind == "note":
            body.append(f"        # {s.t:.1f}s: {s.text}")
            continue
        gap = min(max(s.t - last_t, 0.2), 1.5)
        body.append(f"        page.wait_for_timeout({int(gap * 1000)})")
        last_t = s.t
        if s.kind == "type":
            body.append(f"        page.keyboard.type({json.dumps(s.text)})  # {s.t:.1f}s")
        elif s.target:
            body.append(f"        {s.kind}(page, {json.dumps(s.target)})  # {s.t:.1f}s")
        else:
            body.append(f"        # TODO {s.t:.1f}s: {s.kind} the element shown in {s.zoom} (no text to find it by)")
    body.append("        # TODO: measure what went wrong and print the values")
    return f'''import sys

from dejabug.harness import NOT_REPRODUCED, REPRODUCED, SETUP_ERROR, click, hover, open_page

URL = {json.dumps(url)}


def main() -> int:
    # steps drafted by dejabug from the video: add missing ones, don't remove or reorder these
    with open_page(URL) as page:
{chr(10).join(body)}
    # TODO: return REPRODUCED if the bug happened, NOT_REPRODUCED if the correct behaviour did
    return SETUP_ERROR


if __name__ == "__main__":
    sys.exit(main())
'''


def load(evidence: Path) -> list[Step]:
    events = [json.loads(l) for l in (evidence / "events.jsonl").read_text(encoding="utf-8").splitlines()]
    return steps_from(events)
